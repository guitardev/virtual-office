/**
 * คำนวณปีงบประมาณไทยจากวันที่ YYYY-MM-DD (ต.ค.-ก.ย.)
 */
export function getHolidayFiscalYear(isoDate: string): number {
  const [yStr, mStr] = isoDate.slice(0, 10).split("-");
  const y = Number(yStr);
  const m = Number(mStr);
  if (!y || !m) return new Date().getFullYear() + 543;
  return m >= 10 ? y + 544 : y + 543;
}

/**
 * รวมปฏิทินวันหยุดราชการเริ่มต้นเข้ากับรายการที่ตั้งค่าเพิ่มเติมหรือยกเลิกในฐานข้อมูล
 */
export function buildHolidayMap(dbHolidays?: ThaiHolidayItem[]): Record<string, string> {
  const merged: Record<string, string> = { ...DEFAULT_THAI_HOLIDAYS };
  if (!Array.isArray(dbHolidays)) return merged;

  for (const item of dbHolidays) {
    const key = String(item.holidayDate || "").slice(0, 10);
    if (!key) continue;
    if (item.isActive === false) {
      delete merged[key];
    } else if (item.name) {
      merged[key] = item.name;
    }
  }
  return merged;
}

/**
 * คืนรายการวันหยุดทั้งหมดของปีงบประมาณที่ระบุ เรียงตามวันที่
 */
export function listHolidaysForFiscalYear(
  fiscalYear: number,
  dbHolidays?: ThaiHolidayItem[]
): ThaiHolidayItem[] {
  const map = buildHolidayMap(dbHolidays);
  const dbMap = new Map<string, ThaiHolidayItem>();
  (dbHolidays || []).forEach((h) => dbMap.set(h.holidayDate.slice(0, 10), h));

  const items: ThaiHolidayItem[] = [];
  for (const [dateStr, name] of Object.entries(map)) {
    const fy = getHolidayFiscalYear(dateStr);
    if (fy === fiscalYear) {
      const fromDb = dbMap.get(dateStr);
      items.push({
        holidayDate: dateStr,
        name,
        fiscalYear: fy,
        isActive: true,
        createdBy: fromDb?.createdBy || "system_seed",
      });
    }
  }

  return items.sort((a, b) => a.holidayDate.localeCompare(b.holidayDate));
}
